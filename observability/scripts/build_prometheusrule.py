"""Wrap the plain Prometheus rule files in a PrometheusRule CR for kube-prometheus-stack.

observability/alerts/*.rules.yaml stay the source of truth (promtool tests run on
them); this script renders observability/kube-prometheus-stack/prometheusrule-minieyes.yaml,
which Argo CD applies next to the kube-prometheus-stack release.

    uv run --no-project --with pyyaml python observability/scripts/build_prometheusrule.py [--check]

--check exits 1 when the committed file is stale (used by the pytest suite and CI).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

OBS = Path(__file__).resolve().parents[1]
ALERTS = OBS / "alerts"
OUTPUT = OBS / "kube-prometheus-stack" / "prometheusrule-minieyes.yaml"

HEADER = (
    "# GENERATED by observability/scripts/build_prometheusrule.py from\n"
    "# observability/alerts/*.rules.yaml. Do not edit by hand.\n"
)


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper: yaml.SafeDumper, value: str) -> yaml.Node:
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def render() -> str:
    groups: list[dict] = []
    for path in sorted(ALERTS.glob("*.rules.yaml")):
        groups.extend(yaml.safe_load(path.read_text(encoding="utf-8"))["groups"])
    manifest = {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {
            "name": "minieyes",
            "namespace": "monitoring",
            # matches kube-prometheus-stack's default ruleSelector as well
            "labels": {"release": "kube-prometheus-stack", "app.kubernetes.io/part-of": "minieyes"},
        },
        "spec": {"groups": groups},
    }
    body = yaml.dump(manifest, Dumper=_Dumper, sort_keys=False, width=1000, allow_unicode=True)
    return HEADER + body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the output is stale")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(f"{OUTPUT} is stale; run build_prometheusrule.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
